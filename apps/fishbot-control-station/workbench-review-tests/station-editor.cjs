// Local acceptance: real native panel, editable document and upstream persistence.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const upstream = createRequire(path.join(__dirname, '../workbench/package.json'));
const { chromium, expect } = upstream('@playwright/test');
const base=process.env.STATION_TEST_URL??'http://127.0.0.1:5187';
(async () => {
  const output = path.join(__dirname, 'output/station-editor'); fs.mkdirSync(output, {recursive:true});
  const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome', headless:true, args:['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport:{width:1600,height:1100},acceptDownloads:true});
    const errors=[]; const writes=[];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {if (!['GET','HEAD'].includes(request.method())) writes.push(request.url());});
    await page.goto(base+'/so101-station');
    const editor = page.getByTestId('panel-mouseenter-container RobotStation!so101station');
    await editor.getByLabel('工作站名称', {exact:true}).waitFor({timeout:90000});
    await editor.getByLabel('工作站名称',{exact:true}).fill('我的搬运场景');
    await editor.getByLabel('X（m）',{exact:true}).fill('0.025');
    await editor.getByRole('button',{name:'保存草稿',exact:true}).click();
    await editor.getByRole('button',{name:'添加障碍',exact:true}).click();
    await editor.getByLabel('对象名称',{exact:true}).fill('桌边挡板');
    await editor.getByRole('button',{name:'撤销',exact:true}).click();
    await editor.getByRole('button',{name:'重做',exact:true}).click();
    assert.equal(await editor.getByLabel('对象名称',{exact:true}).inputValue(),'桌边挡板');
    await editor.getByRole('button',{name:'添加步骤',exact:true}).click();
    await editor.getByRole('button',{name:'上移步骤 9',exact:true}).click();
    const downloadPromise = page.waitForEvent('download');
    await editor.getByRole('button',{name:'导出 JSON',exact:true}).click();
    const download = await downloadPromise; const file=path.join(output,'station.json'); await download.saveAs(file);
    const exported = JSON.parse(fs.readFileSync(file,'utf8'));
    assert.equal(exported.station.name,'我的搬运场景');
    assert.equal(exported.station.program.length,9);
    assert(exported.station.nodes.some(n => n.name==='桌边挡板'));
    assert.equal(exported.station.nodes.find(n=>n.id==='cube').position[0],0.025);
    await editor.getByRole('button',{name:'保存草稿',exact:true}).click();
    await editor.getByText('草稿与当前布局已保存，刷新页面可继续编辑。也可导出 JSON 备份。',{exact:true}).waitFor();
    console.log('saved URL', page.url());

    await page.screenshot({path:path.join(output,'before-reload.png')});
    await page.reload();
    console.log('reloaded URL', page.url());
    await editor.getByLabel('工作站名称',{exact:true}).waitFor({timeout:30000});
    await expect(editor.getByLabel('工作站名称',{exact:true})).toHaveValue('我的搬运场景',{timeout:15000});
    const restoredDownload = page.waitForEvent('download');
    await editor.getByRole('button',{name:'导出 JSON',exact:true}).click();
    const restoredPath = await (await restoredDownload).path();
    assert.deepEqual(JSON.parse(fs.readFileSync(restoredPath,'utf8')),exported);
    exported.station.name='JSON 手工修改';
    await editor.locator('input[type=file]').setInputFiles({name:'edited.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
    await page.getByText('工作站已导入，可以继续编辑。',{exact:true}).waitFor();
    assert.equal(await editor.getByLabel('工作站名称',{exact:true}).inputValue(),'JSON 手工修改');
    await editor.locator('input[type=file]').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{bad')});
    await editor.getByRole('alert').filter({hasText:/Expected|JSON.*position/}).waitFor();
    assert.equal(await editor.getByLabel('工作站名称',{exact:true}).inputValue(),'JSON 手工修改');
    await editor.getByText('场景与程序',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
    const mobile = await browser.newPage({viewport:{width:390,height:844}});
    mobile.on('pageerror',error=>errors.push(error.message));
    await mobile.goto(base+'/so101-station-mobile');
    const narrow=mobile.getByTestId('panel-mouseenter-container RobotStation!so101station');
    await narrow.getByLabel('工作站名称',{exact:true}).waitFor({timeout:60000});
    await narrow.getByRole('button',{name:'添加目标点',exact:true}).click();
    await narrow.getByLabel('对象名称',{exact:true}).fill('手机目标');
    await narrow.getByText('场景与程序',{exact:true}).scrollIntoViewIfNeeded();
    await mobile.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
    assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.deepEqual(errors,[]);
    assert(writes.every(url=>['/api/so101/preview','/api/so101/scene-mode'].includes(new URL(url).pathname)), 'Editing may update geometry only; it must never start motion');
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({passed:true,checks:['edit','undo-redo','add-object','reorder','export','refresh','import','invalid-import-preserves-draft','mobile-edit','no-page-errors','no-motion-writes'],errors,writes},null,2));
    console.log('Station editor: 11 browser checks passed.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
