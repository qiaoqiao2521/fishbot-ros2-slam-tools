// Actual native 3D -> editable draft -> original physical executor acceptance.
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');const {createRequire}=require('node:module');
const upstream=createRequire(path.join(__dirname,'../workbench/package.json'));
const {chromium,expect}=upstream('@playwright/test');
const base=process.env.STATION_TEST_URL??'http://127.0.0.1:5187';
const out=path.join(__dirname,'output/station-live');fs.mkdirSync(out,{recursive:true});
const result={passed:false,tasks:[],posts:[],pageErrors:[],meshes:[],checks:[]};
const save=()=>fs.writeFileSync(path.join(out,'result.json'),JSON.stringify(result,null,2));
const geometry=scene=>JSON.stringify((scene?.entities??[]).map(({timestamp,metadata,...entity})=>entity));
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1100},acceptDownloads:true});
  page.on('pageerror',e=>result.pageErrors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST')result.posts.push({url:r.url(),body:r.postDataJSON()});});
  page.on('response',r=>{if(r.url().includes('/api/so101/meshes/'))result.meshes.push({file:r.url().split('/').at(-1),status:r.status()});});
  const state=async()=>await(await page.request.get(base+'/api/so101/scene-state')).json();
  const task=async id=>await(await page.request.get(base+'/api/so101/tasks/'+id)).json();
  await page.goto(base+'/so101-station');
  const panel=page.getByTestId('panel-mouseenter-container RobotStation!so101station');
  const run=panel.getByRole('button',{name:'规划并运行仿真',exact:true});
  await expect(run).toBeEnabled({timeout:90000});
  await panel.getByRole('button',{name:'编辑预览',exact:true}).click();
  await expect.poll(async()=>{const s=await state();return s.mode==='draft'&&s.scene?.entities?.[0]?.models?.length;},{timeout:30000}).toBe(17);
  await expect.poll(()=>new Set(result.meshes.filter(m=>m.status===200).map(m=>m.file)).size,{timeout:30000}).toBe(13);
  await page.screenshot({path:path.join(out,'initial.png')});
  const downloaded=page.waitForEvent('download');
  await panel.getByRole('button',{name:'导出 JSON',exact:true}).click();
  const original=JSON.parse(fs.readFileSync(await(await downloaded).path(),'utf8'));
  const before=await state();
  await panel.getByLabel('X（m）',{exact:true}).fill('0.005');
  await expect.poll(async()=>geometry((await state()).scene),{timeout:30000}).not.toBe(geometry(before.scene));
  let edited=await state();
  assert(edited.scene.entities[0].cubes.some(c=>Math.abs(c.pose.position.x-.245)<1e-9&&Math.abs(c.pose.position.y+.13)<1e-9));
  const cubes=edited.scene.entities[0].cubes.length;
  await panel.getByRole('button',{name:'添加障碍',exact:true}).click();
  await expect.poll(async()=>(await state()).scene?.entities?.[0]?.cubes?.length,{timeout:30000}).toBe(cubes+1);
  assert.equal(result.posts.filter(p=>p.url.includes('/api/so101/tasks')).length,0);
  await page.screenshot({path:path.join(out,'draft-edit.png')});
  result.checks.push('native-17-robot-mesh-instances','all-13-original-stl-loaded','edited-cube-and-obstacle-stream-to-3d-without-motion');save();
  await panel.locator('input[type=file]').setInputFiles({name:'original.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(original))});
  await expect.poll(async()=>(await state()).scene?.entities?.[0]?.cubes?.length,{timeout:30000}).toBe(cubes);
  const submitted=page.waitForResponse(r=>r.url()===base+'/api/so101/tasks'&&r.request().method()==='POST');
  await run.click();const first=await(await submitted).json();result.tasks.push({id:first.id});save();
  await expect.poll(async()=>{const s=await state();return s.taskId===first.id&&s.mode==='task'&&s.scene_seq>1;},{timeout:60000}).toBe(true);
  const moving=await state();const movingGeometry=geometry(moving.scene);
  const previewPosts=result.posts.filter(p=>p.url.endsWith('/preview')).length;
  // Editing an unsubmitted draft must not change the running source or request previews.
  await panel.getByLabel('工作站名称',{exact:true}).fill('仅修改草稿，不替换运行画面');
  await expect.poll(async()=>(await state()).simulation_s,{timeout:60000}).toBeGreaterThan(moving.simulation_s+1);
  const later=await state();assert.equal(later.taskId,first.id);assert.notEqual(geometry(later.scene),movingGeometry);
  assert.equal(result.posts.filter(p=>p.url.endsWith('/preview')).length,previewPosts);
  await page.screenshot({path:path.join(out,'running.png')});
  await page.reload();await expect(panel).toContainText(first.id,{timeout:60000});
  assert.equal(result.posts.filter(p=>p.url===base+'/api/so101/tasks').length,1);
  await expect.poll(async()=>{const s=await task(first.id);result.tasks[0]=s;save();return s.status;},{timeout:180000,intervals:[1000,1500]}).toBe('succeeded');
  const successful=result.tasks[0];assert.equal(successful.report.passed,true);assert.equal(successful.report.safety_stop,false);
  assert.equal(successful.report.controller_done,true);assert.equal(successful.report.place_success,true);assert.equal(successful.scene_final,true);
  await expect.poll(async()=>(await state()).scene_seq,{timeout:10000}).toBe(successful.scene_seq);
  assert.equal(geometry((await state()).scene),geometry(successful.scene));
  assert(successful.object_xyz_m[1]>.1,'Payload must actually reach the blue tray');
  const video=await page.request.get(base+successful.artifacts.video,{headers:{Range:'bytes=0-511'}});assert.equal(video.status(),206);
  await expect(panel.getByRole('region',{name:'当前仿真任务'})).toContainText('执行完成',{timeout:10000});
  await page.screenshot({path:path.join(out,'success.png')});
  result.checks.push('real-full-grasp-place-detach-return','running-model-changes-with-physics','draft-edits-do-not-replace-running-scene','reload-does-not-repeat-task','actual-final-payload-in-blue-tray');save();
  const next=page.waitForResponse(r=>r.url()===base+'/api/so101/tasks'&&r.request().method()==='POST');
  await run.click();const second=await(await next).json();result.tasks.push({id:second.id});save();
  await expect.poll(async()=>(await task(second.id)).simulation_s??0,{timeout:60000}).toBeGreaterThan(2);
  await panel.getByRole('button',{name:'取消任务',exact:true}).click();
  await expect.poll(async()=>{const s=await task(second.id);result.tasks[1]=s;save();return s.status;},{timeout:90000,intervals:[500,1000]}).toBe('cancelled');
  const cancelled=result.tasks[1];assert.equal(cancelled.scene_final,true);assert.equal(cancelled.scene_time_s,cancelled.simulation_s);
  await expect.poll(async()=>(await state()).scene_seq,{timeout:10000}).toBe(cancelled.scene_seq);
  const frozen=await state();assert.equal(geometry(frozen.scene),geometry(cancelled.scene));
  // Explicitly reselect the same task after a draft preview to check source restoration.
  await panel.getByRole('button',{name:'编辑预览',exact:true}).click();await expect.poll(async()=>(await state()).mode).toBe('draft');
  await panel.getByRole('button',{name:'当前任务',exact:true}).click();
  await expect.poll(async()=>geometry((await state()).scene),{timeout:15000}).toBe(geometry(frozen.scene));
  const finalSeq=(await state()).scene_seq;
  await expect.poll(async()=>{const s=await state();return s.scene_seq===finalSeq&&geometry(s.scene)===geometry(frozen.scene);},{intervals:[1200]}).toBe(true);
  await page.screenshot({path:path.join(out,'cancelled.png')});
  const mobile=await browser.newPage({viewport:{width:390,height:844}});mobile.on('pageerror',e=>result.pageErrors.push(e.message));
  const mobileMeshes=new Set();mobile.on('response',r=>{if(r.url().includes('/api/so101/meshes/')&&r.status()===200)mobileMeshes.add(r.url());});
  await mobile.goto(base+'/so101-station-mobile');
  await expect(mobile.getByRole('button',{name:'编辑预览',exact:true})).toBeVisible({timeout:60000});
  await expect.poll(()=>mobile.locator('canvas').count(),{timeout:30000}).toBeGreaterThan(0);
  await expect.poll(()=>mobileMeshes.size,{timeout:30000}).toBe(13);
  await mobile.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
  assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(result.pageErrors,[]);assert(result.meshes.every(m=>m.status===200));
  assert.equal(result.posts.filter(p=>p.url===base+'/api/so101/tasks').length,2);
  assert.equal(result.posts.filter(p=>p.url.endsWith('/cancel')).length,1);
  result.checks.push('cancel-holds-last-actual-pose','switch-draft-and-back-restores-cancelled-pose','mobile-native-3d-no-overflow','no-page-errors-or-mesh-failures');result.passed=true;save();
  console.log(JSON.stringify({passed:true,checks:result.checks,tasks:result.tasks.map(t=>({id:t.id,status:t.status,simulation_s:t.simulation_s,scene_seq:t.scene_seq}))}));
 }finally{save();await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
